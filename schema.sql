-- Punchcard database schema (Postgres / Supabase). Safe to run more than once:
-- `npm run db:setup` runs it, or paste it into the Supabase SQL editor.

CREATE TABLE IF NOT EXISTS staff (
  id     TEXT PRIMARY KEY,
  name   TEXT NOT NULL,
  role   TEXT NOT NULL,
  pin    TEXT NOT NULL,
  rate   DOUBLE PRECISION NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  tone   INTEGER NOT NULL DEFAULT 0,
  email  TEXT NOT NULL DEFAULT '',
  phone  TEXT NOT NULL DEFAULT '',
  pos    BIGINT GENERATED BY DEFAULT AS IDENTITY  -- insertion order, for listing
);

CREATE TABLE IF NOT EXISTS shifts (
  id       TEXT PRIMARY KEY,
  staff_id TEXT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  date     TEXT NOT NULL,             -- YYYY-MM-DD
  start    TEXT NOT NULL,             -- HH:MM
  "end"    TEXT NOT NULL,             -- HH:MM
  area     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS shifts_date ON shifts(date);
CREATE INDEX IF NOT EXISTS shifts_staff ON shifts(staff_id);

CREATE TABLE IF NOT EXISTS entries (
  id           TEXT PRIMARY KEY,
  staff_id     TEXT NOT NULL,         -- no FK: timesheets outlive deleted staff
  clock_in     BIGINT NOT NULL,       -- epoch ms
  clock_out    BIGINT,                -- epoch ms, NULL while on the clock
  breaks       TEXT NOT NULL DEFAULT '[]', -- JSON [{start, end}]
  break_edited BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS entries_in ON entries(clock_in);

CREATE TABLE IF NOT EXISTS notifications (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  staff_id   TEXT NOT NULL,
  week_start TEXT NOT NULL,             -- YYYY-MM-DD (Monday)
  channel    TEXT NOT NULL,             -- 'email'
  recipient  TEXT NOT NULL,
  status     TEXT NOT NULL,             -- 'sent' | 'preview' | 'failed'
  error      TEXT,
  roster     TEXT NOT NULL,             -- fingerprint of the shifts that were sent
  sent_at    BIGINT NOT NULL            -- epoch ms
);
CREATE INDEX IF NOT EXISTS notifications_week ON notifications(week_start, staff_id);

CREATE TABLE IF NOT EXISTS admins (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email      TEXT NOT NULL,
  name       TEXT NOT NULL DEFAULT '',
  password   TEXT NOT NULL,           -- scrypt hash (see auth.js)
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS admins_email ON admins(lower(email));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,        -- sha256 of the cookie value; the raw token is never stored
  admin_id   BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

-- Failed login / PIN attempts. Kept in the database because serverless
-- instances don't share memory.
CREATE TABLE IF NOT EXISTS rate_limits (
  key      TEXT PRIMARY KEY,          -- e.g. 'pin:203.0.113.5'
  first_at BIGINT NOT NULL,           -- epoch ms of the first failure in the window
  count    INTEGER NOT NULL
);

-- Supabase publishes the public schema through its REST API. With RLS on and
-- no policies, that API can't read or change anything; the app connects as the
-- database owner, which bypasses RLS.
ALTER TABLE staff         ENABLE ROW LEVEL SECURITY;
ALTER TABLE shifts        ENABLE ROW LEVEL SECURITY;
ALTER TABLE entries       ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE admins        ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions      ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits   ENABLE ROW LEVEL SECURITY;
